import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { api, ApiRequestError, getPasscode, onUnauthorized, PASSCODE_KEY, parseRetryAfter, restoreSession, setPasscode, upload } from './client'

function jsonResponse(status: number, body: unknown, headers: Record<string, string> = {}): Response {
  return new Response(body === null ? '' : JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json', ...headers } })
}

function headersOf(call: unknown[]): Record<string, string> {
  return (call[1] as RequestInit).headers as Record<string, string>
}

describe('fetch client', () => {
  let fetchMock: ReturnType<typeof vi.fn>

  beforeEach(() => {
    fetchMock = vi.fn()
    vi.stubGlobal('fetch', fetchMock)
    setPasscode('s3cret')
  })

  afterEach(() => {
    vi.unstubAllGlobals()
  })

  it('keeps the passcode in memory and removes any legacy sessionStorage value', () => {
    sessionStorage.setItem(PASSCODE_KEY, 'legacy')
    const targets: Storage[] = []
    const spy = vi.spyOn(Object.getPrototypeOf(sessionStorage) as Storage, 'setItem').mockImplementation(function (this: Storage) {
      targets.push(this)
    })
    setPasscode('other')
    spy.mockRestore()
    expect(targets).toEqual([])
    expect(sessionStorage.getItem(PASSCODE_KEY)).toBeNull()
    expect(getPasscode()).toBe('other')
  })

  it('sends Bearer on GET without the mutation header', async () => {
    fetchMock.mockResolvedValue(jsonResponse(200, { ok: true }))
    await api.library()
    const call = fetchMock.mock.calls[0] ?? []
    expect(call[0]).toBe('/api/library')
    expect(headersOf(call).Authorization).toBe('Bearer s3cret')
    expect(headersOf(call)['X-Scalar-Request']).toBeUndefined()
  })

  it('adds X-Scalar-Request: 1 on POST and DELETE', async () => {
    fetchMock.mockResolvedValue(jsonResponse(200, { paused: true, alreadyPaused: false, at: '2026-10-06T00:00:00Z' }))
    await api.pause()
    let call = fetchMock.mock.calls[0] ?? []
    expect((call[1] as RequestInit).method).toBe('POST')
    expect(headersOf(call).Authorization).toBe('Bearer s3cret')
    expect(headersOf(call)['X-Scalar-Request']).toBe('1')
    expect(headersOf(call)['Content-Type']).toBe('application/json')

    fetchMock.mockResolvedValue(jsonResponse(200, { deleted: true }))
    await api.deleteEpisode('scalar-clues-001', 2)
    call = fetchMock.mock.calls[1] ?? []
    expect(call[0]).toBe('/api/library/episodes/scalar-clues-001/2')
    expect((call[1] as RequestInit).method).toBe('DELETE')
    expect(headersOf(call)['X-Scalar-Request']).toBe('1')
  })

  it('restores from the cookie when browser storage is unavailable and shares an in-flight restore', async () => {
    const getItem = vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new DOMException('blocked') })
    fetchMock.mockResolvedValue(jsonResponse(200, { authenticated: true }))
    const first = restoreSession()
    const second = restoreSession()
    await Promise.all([first, second])
    expect(fetchMock).toHaveBeenCalledTimes(1)
    getItem.mockRestore()
  })

  it('migrates a legacy passcode once and rechecks the cookie on later restores', async () => {
    sessionStorage.setItem(PASSCODE_KEY, 'legacy-passcode')
    fetchMock
      .mockResolvedValueOnce(jsonResponse(200, { authenticated: false }))
      .mockResolvedValueOnce(jsonResponse(200, { authenticated: true }))
      .mockResolvedValueOnce(jsonResponse(200, { authenticated: true }))
    expect(await restoreSession()).toBe(true)
    expect(fetchMock).toHaveBeenCalledTimes(2)
    expect(headersOf(fetchMock.mock.calls[1] ?? []).Authorization).toBe('Bearer legacy-passcode')
    expect(sessionStorage.getItem(PASSCODE_KEY)).toBeNull()
    expect(getPasscode()).toBeNull()
    expect(await restoreSession()).toBe(true)
    expect(fetchMock).toHaveBeenCalledTimes(3)
  })

  it('sends the exact full-SHA update confirmation generated by the API client', async () => {
    fetchMock.mockResolvedValue(jsonResponse(202, { queued: true }))
    await api.updateStart('a'.repeat(40))
    expect(JSON.parse((fetchMock.mock.calls[0]?.[1] as RequestInit).body as string)).toEqual({ confirm: `UPDATE TO ${'a'.repeat(40)}` })
  })

  it('posts batch.json bytes as application/json', async () => {
    fetchMock.mockResolvedValue(jsonResponse(200, { batchId: 'b', expected: [], problems: [], warnings: [], merge: [] }))
    await api.importBatch('{"batchId":"b"}')
    const call = fetchMock.mock.calls[0] ?? []
    expect((call[1] as RequestInit).body).toBe('{"batchId":"b"}')
    expect(headersOf(call)['Content-Type']).toBe('application/json')
  })

  it('clears the passcode on 401 and notifies listeners', async () => {
    const listener = vi.fn()
    const off = onUnauthorized(listener)
    fetchMock.mockResolvedValue(jsonResponse(401, { error: 'That passcode was not accepted.', nextAction: null }))
    await expect(api.dashboard()).rejects.toMatchObject({ status: 401, message: 'That passcode was not accepted.' })
    expect(getPasscode()).toBeNull()
    expect(sessionStorage.getItem(PASSCODE_KEY)).toBeNull()
    expect(listener).toHaveBeenCalledOnce()
    off()
  })

  it('shows the Retry-After wait on 429', async () => {
    fetchMock.mockResolvedValue(jsonResponse(429, { error: 'Too many attempts', nextAction: null }, { 'Retry-After': '32' }))
    const error = await api.dashboard().catch((e: unknown) => e)
    expect(error).toBeInstanceOf(ApiRequestError)
    expect((error as ApiRequestError).retryAfterSeconds).toBe(32)
    expect((error as ApiRequestError).message).toBe('Too many attempts. Wait 32 seconds before trying again.')
    expect(getPasscode()).toBe('s3cret')
  })

  it('renders the backend {error, nextAction}', async () => {
    fetchMock.mockResolvedValue(jsonResponse(409, { error: 'An approval is already pending.', nextAction: 'Wait for its result.' }))
    await expect(api.approveDraft('abc', 'APPROVE abc')).rejects.toMatchObject({
      status: 409,
      message: 'An approval is already pending.',
      nextAction: 'Wait for its result.',
    })
  })

  it('serialises history filters into the query string', async () => {
    fetchMock.mockResolvedValue(jsonResponse(200, { rows: [], total: 0, truncated: false, displayTimezone: 'UTC' }))
    await api.history({ platform: 'x', q: 'bolivia' })
    expect(fetchMock.mock.calls[0]?.[0]).toBe('/api/history?platform=x&q=bolivia&format=json')
  })

  it('reads and writes the post stats controls with the mutation header', async () => {
    const status = { enabled: true, pending: null, lastRun: null, timer: null, pathActive: true }
    fetchMock.mockImplementation(() => Promise.resolve(jsonResponse(200, status)))
    expect(await api.getMetricsStatus()).toEqual(status)
    let call = fetchMock.mock.calls[0] ?? []
    expect(call[0]).toBe('/api/metrics/status')
    expect((call[1] as RequestInit).method).toBe('GET')
    expect(headersOf(call)['X-Scalar-Request']).toBeUndefined()

    await api.setMetricsEnabled(false)
    call = fetchMock.mock.calls[1] ?? []
    expect(call[0]).toBe('/api/metrics/enabled')
    expect((call[1] as RequestInit).method).toBe('PUT')
    expect((call[1] as RequestInit).body).toBe('{"enabled":false}')
    expect(headersOf(call)['X-Scalar-Request']).toBe('1')

    await api.requestMetricsRead(30)
    call = fetchMock.mock.calls[2] ?? []
    expect(call[0]).toBe('/api/metrics/read')
    expect((call[1] as RequestInit).method).toBe('POST')
    expect((call[1] as RequestInit).body).toBe('{"backfill":30}')
    expect(headersOf(call)['X-Scalar-Request']).toBe('1')

    await api.requestMetricsRead()
    expect(((fetchMock.mock.calls[3] ?? [])[1] as RequestInit).body).toBe('{}')
  })

  it('surfaces 409 and 422 from a stats read request as ApiRequestError', async () => {
    fetchMock.mockResolvedValueOnce(jsonResponse(409, { error: 'A read is already waiting.', nextAction: null }))
    await expect(api.requestMetricsRead()).rejects.toMatchObject({ status: 409, message: 'A read is already waiting.' })
    fetchMock.mockResolvedValueOnce(jsonResponse(422, { error: 'backfill must be 0–93 days.', nextAction: null }))
    await expect(api.requestMetricsRead(120)).rejects.toMatchObject({ status: 422, message: 'backfill must be 0–93 days.' })
  })

  it('parses Retry-After as seconds or HTTP date', () => {
    expect(parseRetryAfter('120')).toBe(120)
    expect(parseRetryAfter(new Date(Date.UTC(2026, 0, 1, 0, 1)).toUTCString(), Date.UTC(2026, 0, 1))).toBe(60)
    expect(parseRetryAfter(null)).toBeNull()
  })
})

class FakeXHR {
  static last: FakeXHR | null = null
  method = ''
  url = ''
  headers: Record<string, string> = {}
  status = 0
  responseText = ''
  responseType = ''
  body: unknown = null
  upload: { onprogress: ((e: ProgressEvent) => void) | null } = { onprogress: null }
  onload: (() => void) | null = null
  onerror: (() => void) | null = null
  onabort: (() => void) | null = null
  private responseHeaders: Record<string, string> = {}
  constructor() {
    FakeXHR.last = this
  }
  open(method: string, url: string) {
    this.method = method
    this.url = url
  }
  setRequestHeader(name: string, value: string) {
    this.headers[name] = value
  }
  getResponseHeader(name: string) {
    return this.responseHeaders[name] ?? null
  }
  send(body: unknown) {
    this.body = body
  }
  abort() {
    this.onabort?.()
  }
  respond(status: number, body: unknown, headers: Record<string, string> = {}) {
    this.status = status
    this.responseText = JSON.stringify(body)
    this.responseHeaders = headers
    this.onload?.()
  }
}

describe('XHR uploads', () => {
  beforeEach(() => {
    vi.stubGlobal('XMLHttpRequest', FakeXHR)
    setPasscode('s3cret')
  })
  afterEach(() => vi.unstubAllGlobals())

  it('PUTs batch files with progress, Content-Type and the same headers', async () => {
    const progress = vi.fn()
    const file = new Blob(['x'.repeat(10)], { type: 'video/mp4' })
    const handle = api.uploadBatchFile('2026-10-pilots', 'video', 'scalar-clues-001.mp4', file, progress)
    const xhr = FakeXHR.last as FakeXHR
    expect(xhr.method).toBe('PUT')
    expect(xhr.url).toBe('/api/library/batches/2026-10-pilots/files/videos/scalar-clues-001.mp4')
    expect(xhr.headers['Content-Type']).toBe('video/mp4')
    expect(xhr.headers.Authorization).toBe('Bearer s3cret')
    expect(xhr.headers['X-Scalar-Request']).toBe('1')
    xhr.upload.onprogress?.({ loaded: 5, total: 10, lengthComputable: true } as ProgressEvent)
    expect(progress).toHaveBeenCalledWith({ loaded: 5, total: 10 })
    xhr.respond(200, { matched: true })
    await expect(handle.promise).resolves.toEqual({ matched: true })
  })

  it('uses image/jpeg for covers and passes the method through', () => {
    api.uploadBatchFile('b', 'cover', 'scalar-clues-001.jpg', new Blob(['x']))
    expect(FakeXHR.last?.headers['Content-Type']).toBe('image/jpeg')
    expect(FakeXHR.last?.url).toBe('/api/library/batches/b/files/covers/scalar-clues-001.jpg')
    upload('POST', '/api/library/batches/b/files/videos/x.mp4', new Blob(['x']), 'video/mp4')
    expect(FakeXHR.last?.method).toBe('POST')
  })

  it('maps upload 401 to a cleared passcode and interruption to a retryable error', async () => {
    const h1 = api.uploadBatchFile('b', 'video', 'scalar-clues-001.mp4', new Blob(['x']))
    FakeXHR.last?.onerror?.()
    await expect(h1.promise).rejects.toMatchObject({ message: 'Upload interrupted.' })
    const h2 = api.uploadBatchFile('b', 'video', 'scalar-clues-001.mp4', new Blob(['x']))
    FakeXHR.last?.respond(401, { error: 'Passcode required', nextAction: null })
    await expect(h2.promise).rejects.toMatchObject({ status: 401 })
    expect(getPasscode()).toBeNull()
  })
})
